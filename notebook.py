def generate_sample_diabetes_data(n_samples=10000):

    np.random.seed(42)

    # Generate features
    data = {}

    # Age (20-80 years)
    data['age'] = np.random.normal(45, 15, n_samples).clip(20, 80)

    # Gender
    data['gender'] = np.random.choice(['Male', 'Female'], n_samples)

    # BMI (15-50)
    data['bmi'] = np.random.normal(25, 5, n_samples).clip(15, 50)

    # Hypertension (0 or 1)
    data['hypertension'] = np.random.binomial(1, 0.3, n_samples)

    # Heart Disease (0 or 1)
    data['heart_disease'] = np.random.binomial(1, 0.2, n_samples)

    # Smoking History
    smoking_options = ['never', 'former', 'current', 'not current', 'ever', 'No Info']
    data['smoking_history'] = np.random.choice(smoking_options, n_samples)

    # HbA1c Level (4-10)
    data['HbA1c_level'] = np.random.normal(5.5, 1.2, n_samples).clip(4, 10)

    # Blood Glucose Level (80-300)
    data['blood_glucose_level'] = np.random.normal(120, 40, n_samples).clip(80, 300)

    df = pd.DataFrame(data)

    # Generate target based on logical rules
    diabetes_prob = (
        0.1 +  # baseline
        0.3 * (df['age'] > 60) +
        0.4 * (df['bmi'] > 30) +
        0.3 * df['hypertension'] +
        0.2 * df['heart_disease'] +
        0.4 * (df['HbA1c_level'] > 6.5) +
        0.5 * (df['blood_glucose_level'] > 140) +
        0.1 * (df['smoking_history'].isin(['current', 'former']))
    )

    diabetes_prob = np.clip(diabetes_prob, 0, 1)
    data['diabetes'] = np.random.binomial(1, diabetes_prob, n_samples)

    return pd.DataFrame(data)

